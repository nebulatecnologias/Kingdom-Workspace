// Generates ops/supabase/seed.sql from the prototype's sample data (ops/prototype/src/data.js).
// Usage: node ops/supabase/scripts/generate-seed.mjs
// The prototype's four synthetic people become the real team (names and roles only; emails are
// placeholders until `npm run user:create` sets the real email and password).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "../../prototype/src/data.js"), "utf8");
const ctx = {};
vm.runInNewContext(`${src}\n;globalThis.__DB = DB;`, ctx);
const DB = ctx.__DB;

/** Deterministic UUID for a prototype id, so the seed is stable and re-runnable. */
const uuid = (id) => {
  const h = createHash("md5").update(`kingdom-ops:${id}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

// Real team (owner's list, 19/11/2026). The first four take the place of the prototype's p1..p4.
const TEAM = [
  { id: "p1", full_name: "Shelton Douglas", job_title: "Direção Operacional", role: "admin", color: "#c9f243", replaces: "Ana Cossa" },
  { id: "p2", full_name: "Domingas Trindade", job_title: "Direção Comercial", role: "admin", color: "#a7d8f0", replaces: "Bruno Macuácua" },
  { id: "p3", full_name: "Maria", job_title: "Assistente Comercial / Vendedora", role: "member", color: "#f6c38b", replaces: "Carla Sitoe" },
  { id: "p4", full_name: "Leonardo", job_title: "Growth", role: "member", color: "#d9b8f2", replaces: "Dário Nhantumbo" },
  { id: "p5", full_name: "Mayra", job_title: "Assistente Administrativa / Vendedora", role: "member", color: "#f2b8c6", replaces: null },
];
const NAME_FIXES = [
  ...TEAM.filter((t) => t.replaces).map((t) => [t.replaces, t.full_name]),
  ["pela Ana", "pelo Shelton"],
];
const fix = (s) => (typeof s === "string" ? NAME_FIXES.reduce((acc, [a, b]) => acc.split(a).join(b), s) : s);

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "object") return `'${JSON.stringify(v, (_, x) => fix(x)).replace(/'/g, "''")}'::jsonb`;
  return `'${String(fix(v)).replace(/'/g, "''")}'`;
};
const ref = (id) => (id ? `'${uuid(id)}'` : "null");

const out = [];
out.push("-- Generated by ops/supabase/scripts/generate-seed.mjs from ops/prototype/src/data.js. Do not edit by hand.");
out.push("-- Team = real people (placeholder emails, no password: they cannot sign in until `npm run user:create`).");
out.push("-- Cards, activity and minutes = the prototype's sample data (clear with ops/supabase/scripts/clear-demo.sql).");
out.push("begin;");
out.push("select set_config('ops.skip_activity', 'on', true);");
out.push("");
out.push("-- Team");
for (const t of TEAM) {
  const email = `${t.full_name.split(" ")[0].normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()}@placeholder.kingdom-ops.invalid`;
  out.push(
    `insert into auth.users (id, instance_id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values (${ref(t.id)}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', ${q(email)}, '', null, '{"provider":"email","providers":["email"]}'::jsonb, ${q({ full_name: t.full_name })}, now(), now(), '', '', '', '')
on conflict (id) do nothing;`,
  );
  out.push(
    `insert into public.profiles (id, full_name, role, job_title, color, active) values (${ref(t.id)}, ${q(t.full_name)}, ${q(t.role)}, ${q(t.job_title)}, ${q(t.color)}, true)
on conflict (id) do update set full_name = excluded.full_name, role = excluded.role, job_title = excluded.job_title, color = excluded.color, active = true;`,
  );
}

out.push("\n-- Pipelines and stages");
for (const p of DB.pipelines) {
  out.push(`insert into public.pipelines (id, slug, name, kind, icon, position) values (${ref(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.kind)}, ${q(p.icon)}, ${p.position}) on conflict (id) do nothing;`);
}
for (const s of DB.pipeline_stages) {
  out.push(
    `insert into public.pipeline_stages (id, pipeline_id, name, position, tone, is_done, is_lost, requires_note, requires_reschedule) values (${ref(s.id)}, ${ref(s.pipeline_id)}, ${q(s.name)}, ${s.position}, ${q(s.tone)}, ${q(s.is_done)}, ${q(s.is_lost)}, ${q(s.requires_note)}, ${q(s.requires_reschedule)}) on conflict (id) do nothing;`,
  );
}

out.push("\n-- Sample cards");
const cols = ["title", "starts_at", "ends_at", "location_kind", "location", "contact_name", "contact_role", "contact_phone", "contact_email", "company_name", "company_sector", "value_cents", "due_at", "description", "position", "stage_changed_at", "created_at"];
for (const c of DB.cards) {
  out.push(
    `insert into public.cards (id, pipeline_id, stage_id, owner_id, created_by, ${cols.join(", ")}) values (${ref(c.id)}, ${ref(c.pipeline_id)}, ${ref(c.stage_id)}, ${ref(c.owner_id)}, ${ref(c.owner_id)}, ${cols.map((k) => q(k === "description" ? c[k] || null : c[k])).join(", ")}) on conflict (id) do nothing;`,
  );
}
for (const p of DB.card_participants) {
  out.push(`insert into public.card_participants (card_id, profile_id) values (${ref(p.card_id)}, ${ref(p.profile_id)}) on conflict do nothing;`);
}

out.push("\n-- Sample history");
for (const a of DB.card_activity) {
  out.push(
    `insert into public.card_activity (id, card_id, actor_id, type, from_stage_id, to_stage_id, note, at) values (${ref(a.id)}, ${ref(a.card_id)}, ${ref(a.actor_id)}, ${q(a.type)}, ${ref(a.from_stage_id)}, ${ref(a.to_stage_id)}, ${q(a.note)}, ${q(a.at)}) on conflict (id) do nothing;`,
  );
}

out.push("\n-- Sample minutes");
for (const m of DB.minutes) {
  out.push(
    `insert into public.minutes (id, card_id, title, held_at, started_at, ended_at, location, attendees, agenda, decisions, actions, next_steps, next_meeting_at, written_by, approved_by, status, finalized_at, created_at, updated_at) values (${ref(m.id)}, ${ref(m.card_id)}, ${q(m.title)}, ${q(m.held_at)}, ${q(m.started_at)}, ${q(m.ended_at)}, ${q(m.location)}, ${q(m.attendees)}, ${q(m.agenda)}, ${q(m.decisions)}, ${q(m.actions)}, ${q(m.next_steps || null)}, ${q(m.next_meeting_at)}, ${ref(m.written_by)}, ${ref(m.approved_by)}, ${q(m.status)}, ${q(m.finalized_at)}, ${q(m.created_at)}, ${q(m.updated_at)}) on conflict (id) do nothing;`,
  );
}
out.push("\ncommit;");

writeFileSync(join(here, "../seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql: ${TEAM.length} people, ${DB.pipelines.length} pipelines, ${DB.pipeline_stages.length} stages, ${DB.cards.length} cards, ${DB.card_activity.length} activity rows, ${DB.minutes.length} minutes`);
